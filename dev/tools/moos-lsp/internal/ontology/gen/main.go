// Command gen reads the mo:os ontology (kb/superset/ontology.json) and emits a Go
// source file of symbol tables (node types, WF categories, port-color matrix,
// nomenclature, invariants) for the language server to consume.
//
// Usage:
//
//	go run ./internal/ontology/gen -ontology ../../../kb/superset/ontology.json -out internal/ontology/symbols.go
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type rawType struct {
	ID         string `json:"id"`
	Stratum    string `json:"stratum"`
	URNPattern string `json:"urn_pattern"`
	URNExample string `json:"urn_example"`
	Ports      struct {
		Out  []string `json:"out"`
		In   []string `json:"in"`
		Self []string `json:"self"`
	} `json:"ports"`
}

type portPair struct {
	SrcPort  string   `json:"src_port"`
	TgtPort  string   `json:"tgt_port"`
	SrcTypes []string `json:"src_types"`
	TgtTypes []string `json:"tgt_types"`
}

type rawWF struct {
	ID              string     `json:"id"`
	Name            string     `json:"name"`
	Description     string     `json:"description"`
	AllowedRewrites []string   `json:"allowed_rewrites"`
	SrcTypes        []string   `json:"src_types"`
	TgtTypes        []string   `json:"tgt_types"`
	SrcPort         string     `json:"src_port"`
	TgtPort         string     `json:"tgt_port"`
	Additional      []portPair `json:"additional_port_pairs"`
}

type rawOntology struct {
	Version string `json:"version"`
	Types   struct {
		S2    []rawType `json:"s2_infrastructure"`
		S1    []rawType `json:"s1_grammar"`
		Inter []rawType `json:"interaction_nodes"`
	} `json:"types"`
	RewriteCategories []rawWF `json:"rewrite_categories"`
	PCC               struct {
		PortColors []string                              `json:"port_colors"`
		Matrix     map[string]map[string]json.RawMessage `json:"matrix"`
	} `json:"port_color_compatibility"`
	Nomenclature struct {
		Use       map[string]string `json:"use"`
		Forbidden []string          `json:"forbidden"`
	} `json:"nomenclature_rules"`
	Invariants map[string]string `json:"five_causal_invariants"`
}

func main() {
	ontPath := flag.String("ontology", "../../../kb/superset/ontology.json", "Path to ontology.json")
	outPath := flag.String("out", "internal/ontology/symbols.go", "Path to write symbols.go")
	flag.Parse()

	data, err := os.ReadFile(*ontPath)
	must(err)
	var o rawOntology
	must(json.Unmarshal(data, &o))

	var b strings.Builder
	emit(&b, &o)

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		// Write unformatted so the error is inspectable.
		_ = os.WriteFile(*outPath, []byte(b.String()), 0o644)
		fmt.Fprintf(os.Stderr, "gofmt failed (wrote unformatted): %v\n", err)
		os.Exit(1)
	}
	must(os.WriteFile(*outPath, src, 0o644))
	fmt.Printf("wrote %s: %d node types, %d WFs, %d port colors\n",
		*outPath, len(o.Types.S2)+len(o.Types.S1)+len(o.Types.Inter), len(o.RewriteCategories), len(o.PCC.PortColors))
}

func emit(b *strings.Builder, o *rawOntology) {
	p := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }

	p("// Code generated by internal/ontology/gen from kb/superset/ontology.json. DO NOT EDIT.\n")
	p("// Regenerate: go run ./internal/ontology/gen -ontology <path> -out internal/ontology/symbols.go\n\n")
	p("package ontology\n\n")
	p("// OntologyVersion is the version of the ontology these tables were generated from.\n")
	p("const OntologyVersion = %q\n\n", o.Version)

	// NodeType + node tables.
	p("// NodeType describes one node type from the operad.\n")
	p("type NodeType struct {\n\tID, Stratum, URNPattern, URNExample string\n\tOutPorts, InPorts []string\n}\n\n")

	all := append(append(append([]rawType{}, o.Types.S2...), o.Types.S1...), o.Types.Inter...)
	sort.Slice(all, func(i, j int) bool { return all[i].ID < all[j].ID })

	p("// NodeTypes maps a type id to its definition.\n")
	p("var NodeTypes = map[string]NodeType{\n")
	for _, t := range all {
		p("\t%q: {ID: %q, Stratum: %q, URNPattern: %q, URNExample: %q, OutPorts: %s, InPorts: %s},\n",
			t.ID, t.ID, t.Stratum, t.URNPattern, t.URNExample, strSlice(t.Ports.Out), strSlice(t.Ports.In))
	}
	p("}\n\n")

	p("// NodeTypeIDs is the sorted list of all node type ids.\n")
	p("var NodeTypeIDs = %s\n\n", strSliceFromTypes(all))

	// WF table.
	p("// PortPair describes one declared source/target port pair for a WF.\n")
	p("type PortPair struct {\n\tSrcPort, TgtPort string\n\tSrcTypes, TgtTypes []string\n}\n\n")
	p("// WF describes one rewrite category (WF01..WF21).\n")
	p("type WF struct {\n\tID, Name, Description string\n\tAllowedRewrites, SrcTypes, TgtTypes []string\n\tPortPairs []PortPair\n}\n\n")

	p("// WFs maps a WF id to its definition.\n")
	p("var WFs = map[string]WF{\n")
	for _, w := range o.RewriteCategories {
		p("\t%q: {ID: %q, Name: %q, Description: %q, AllowedRewrites: %s, SrcTypes: %s, TgtTypes: %s, PortPairs: %s},\n",
			w.ID, w.ID, w.Name, w.Description, strSlice(w.AllowedRewrites), strSlice(w.SrcTypes), strSlice(w.TgtTypes), pairSlice(wfPairs(w)))
	}
	p("}\n\n")

	p("// WFOrder is the WF ids in declaration order (WF01..WF21).\n")
	var order []string
	for _, w := range o.RewriteCategories {
		order = append(order, w.ID)
	}
	p("var WFOrder = %s\n\n", strSlice(order))

	// Port colors + matrix.
	p("// PortColors is the set of port colors.\n")
	p("var PortColors = %s\n\n", strSlice(o.PCC.PortColors))

	p("// PortColorMatrix[src][tgt] is one of: \"true\", \"false\", \"wf15_only\", \"sink_only\".\n")
	p("var PortColorMatrix = map[string]map[string]string{\n")
	srcKeys := sortedKeys(o.PCC.Matrix)
	for _, src := range srcKeys {
		p("\t%q: {", src)
		row := o.PCC.Matrix[src]
		tgtKeys := sortedKeys(row)
		for _, tgt := range tgtKeys {
			p("%q: %q, ", tgt, normColor(row[tgt]))
		}
		p("},\n")
	}
	p("}\n\n")

	// Nomenclature.
	p("// UseVocab maps a canonical term to its definition.\n")
	p("var UseVocab = map[string]string{\n")
	for _, k := range sortedKeys(o.Nomenclature.Use) {
		p("\t%q: %q,\n", k, o.Nomenclature.Use[k])
	}
	p("}\n\n")

	p("// ForbiddenVocab maps a forbidden token to the full nomenclature entry it came from.\n")
	p("var ForbiddenVocab = map[string]string{\n")
	for _, tok := range sortedKeys(forbiddenTokens(o.Nomenclature.Forbidden)) {
		p("\t%q: %q,\n", tok, forbiddenTokens(o.Nomenclature.Forbidden)[tok])
	}
	p("}\n\n")

	// Invariants.
	p("// Invariants maps CI ids (CI1..CI5) to their statements.\n")
	p("var Invariants = map[string]string{\n")
	for _, k := range sortedKeys(o.Invariants) {
		p("\t%q: %q,\n", k, o.Invariants[k])
	}
	p("}\n\n")

	// Derived: rewrite types, port->WF, known ports.
	p("// RewriteTypes is the four-rewrite opcode set.\n")
	p("var RewriteTypes = []string{\"ADD\", \"LINK\", \"MUTATE\", \"UNLINK\"}\n\n")

	srcPortToWF := map[string]string{}
	known := map[string]bool{}
	for _, w := range o.RewriteCategories {
		for _, pr := range wfPairs(w) {
			if _, ok := srcPortToWF[pr.SrcPort]; !ok {
				srcPortToWF[pr.SrcPort] = w.ID
			}
			known[pr.SrcPort] = true
			known[pr.TgtPort] = true
		}
	}
	for _, t := range all {
		for _, pt := range append(append([]string{}, t.Ports.Out...), t.Ports.In...) {
			known[pt] = true
		}
	}
	p("// SrcPortToWF maps a source port name to the first WF that declares it.\n")
	p("var SrcPortToWF = map[string]string{\n")
	for _, k := range sortedKeys(srcPortToWF) {
		p("\t%q: %q,\n", k, srcPortToWF[k])
	}
	p("}\n\n")

	p("// KnownPorts is the set of all port names appearing in the operad.\n")
	p("var KnownPorts = map[string]bool{\n")
	for _, k := range sortedKeys(known) {
		p("\t%q: true,\n", k)
	}
	p("}\n")
}

func wfPairs(w rawWF) []portPair {
	seen := map[[2]string]bool{}
	var out []portPair
	add := func(s, t string, srcTypes, tgtTypes []string) {
		if s == "" && t == "" {
			return
		}
		key := [2]string{s, t}
		if !seen[key] {
			seen[key] = true
			out = append(out, portPair{SrcPort: s, TgtPort: t, SrcTypes: srcTypes, TgtTypes: tgtTypes})
		}
	}
	add(w.SrcPort, w.TgtPort, w.SrcTypes, w.TgtTypes)
	for _, a := range w.Additional {
		add(a.SrcPort, a.TgtPort, a.SrcTypes, a.TgtTypes)
	}
	return out
}

// forbiddenTokens splits entries like "binding (for graph)" and "_ref/_refs (...)"
// into bare tokens mapped to their original note.
func forbiddenTokens(entries []string) map[string]string {
	out := map[string]string{}
	for _, e := range entries {
		head := e
		if i := strings.Index(e, " ("); i >= 0 {
			head = e[:i]
		}
		head = strings.TrimSpace(head)
		for _, tok := range strings.Split(head, "/") {
			tok = strings.TrimSpace(tok)
			if tok != "" {
				out[tok] = e
			}
		}
	}
	return out
}

func normColor(raw json.RawMessage) string {
	s := strings.TrimSpace(string(raw))
	switch s {
	case "true":
		return "true"
	case "false":
		return "false"
	}
	var str string
	if err := json.Unmarshal(raw, &str); err == nil {
		return str
	}
	return s
}

func strSlice(v []string) string {
	if len(v) == 0 {
		return "nil"
	}
	parts := make([]string, len(v))
	for i, s := range v {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

func strSliceFromTypes(ts []rawType) string {
	ids := make([]string, len(ts))
	for i, t := range ts {
		ids[i] = t.ID
	}
	return strSlice(ids)
}

func pairSlice(pairs []portPair) string {
	if len(pairs) == 0 {
		return "nil"
	}
	parts := make([]string, len(pairs))
	for i, p := range pairs {
		parts[i] = fmt.Sprintf("{SrcPort: %q, TgtPort: %q, SrcTypes: %s, TgtTypes: %s}", p.SrcPort, p.TgtPort, strSlice(p.SrcTypes), strSlice(p.TgtTypes))
	}
	return "[]PortPair{" + strings.Join(parts, ", ") + "}"
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
